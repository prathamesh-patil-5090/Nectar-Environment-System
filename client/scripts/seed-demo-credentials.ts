/**
 * Seed demo login credentials for every role into MongoDB (`users` collection)
 * using `server/.env` (MONGODB_URI), and export docs copies for QA.
 *
 * Usage (from repo root):
 *   npm run seed:credentials
 *   npx tsx client/scripts/seed-demo-credentials.ts
 *
 * Options:
 *   --docs-only   Skip Mongo; only write docs/*
 *   --mongo-only  Skip docs; only upsert Mongo users
 */

import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  DEMO_USERS,
  DEMO_USERS_HIDDEN,
  ROLE_LABELS,
  type DemoUser,
} from "../lib/auth";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "../..");
const outDir = join(repoRoot, "docs");
const serverRoot = join(repoRoot, "server");
const require = createRequire(join(serverRoot, "package.json"));

type CredentialRow = DemoUser & {
  visibleOnLogin: boolean;
  roleLabel: string;
  plant: string;
};

function plantOf(u: DemoUser): string {
  if (!u.siteId) return "org-wide";
  if (u.siteId === "s-etp") return "ETP";
  if (u.siteId === "s-ro") return "RO";
  if (u.siteId === "s-mee") return "MEE";
  return u.siteId;
}

function rows(): CredentialRow[] {
  const visible = DEMO_USERS.map((u) => ({
    ...u,
    visibleOnLogin: true,
    roleLabel: ROLE_LABELS[u.role],
    plant: plantOf(u),
  }));
  const hidden = DEMO_USERS_HIDDEN.map((u) => ({
    ...u,
    visibleOnLogin: false,
    roleLabel: ROLE_LABELS[u.role],
    plant: plantOf(u),
  }));
  return [...visible, ...hidden];
}

function toCsv(data: CredentialRow[]): string {
  const header = [
    "email",
    "password",
    "name",
    "role",
    "roleLabel",
    "plant",
    "siteId",
    "employeeId",
    "visibleOnLogin",
  ];
  const escape = (v: string) => `"${String(v).replaceAll('"', '""')}"`;
  const lines = data.map((r) =>
    [
      r.email,
      r.password,
      r.name,
      r.role,
      r.roleLabel,
      r.plant,
      r.siteId ?? "",
      r.employeeId ?? "",
      r.visibleOnLogin ? "yes" : "no",
    ]
      .map(escape)
      .join(","),
  );
  return [header.join(","), ...lines].join("\n") + "\n";
}

