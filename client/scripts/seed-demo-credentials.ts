function writeDocs(data: CredentialRow[]) {
  mkdirSync(outDir, { recursive: true });
  const jsonPath = join(outDir, "demo-credentials.json");
  const csvPath = join(outDir, "demo-credentials.csv");
  const mdPath = join(outDir, "demo-credentials.md");

  writeFileSync(
    jsonPath,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        sharedPassword: "nectar2026",
        rosterToday: "2026-09-23",
        mongoCollection: "users",
        count: data.length,
        accounts: data,
      },
      null,
      2,
    ) + "\n",
    "utf8",
  );
  writeFileSync(csvPath, toCsv(data), "utf8");
  writeFileSync(mdPath, toMarkdown(data), "utf8");

  console.log(`Docs written (${data.length} accounts):`);
  console.log(`  ${jsonPath}`);
  console.log(`  ${csvPath}`);
  console.log(`  ${mdPath}`);
}

async function seedMongo(data: CredentialRow[]) {
  const dotenv = require("dotenv") as typeof import("dotenv");
  const mongoose = require("mongoose") as typeof import("mongoose");

  dotenv.config({ path: join(serverRoot, ".env") });

  const uri = process.env.MONGODB_URI;
  if (!uri) {
    throw new Error(
      "MONGODB_URI missing. Set it in server/.env (see Atlas connection string).",
    );
  }

  const redacted = uri.replace(/:([^:@]+)@/, ":****@");
  console.log(`Connecting to MongoDB: ${redacted}`);

  await mongoose.connect(uri, { dbName: "nectar_enviro" });

  const UserSchema = new mongoose.Schema(
    {
      email: { type: String, required: true, unique: true, lowercase: true },
      password: { type: String, required: true },
      name: { type: String, required: true },
      role: { type: String, required: true },
      siteId: String,
      employeeId: String,
      visibleOnLogin: { type: Boolean, default: true },
      active: { type: Boolean, default: true },
    },
    { collection: "users", timestamps: true },
  );

  const UserModel =
    mongoose.models.User ?? mongoose.model("User", UserSchema, "users");

  let upserted = 0;
  for (const row of data) {
    await UserModel.findOneAndUpdate(
      { email: row.email.toLowerCase() },
      {
        $set: {
          email: row.email.toLowerCase(),
          password: row.password,
          name: row.name,
          role: row.role,
          siteId: row.siteId,
          employeeId: row.employeeId,
          visibleOnLogin: row.visibleOnLogin,
          active: true,
        },
      },
      { upsert: true, new: true },
    );
    upserted += 1;
  }

  const total = await UserModel.countDocuments({});
  console.log(`Mongo upserted ${upserted} accounts into nectar_enviro.users (total now ${total}).`);

  await mongoose.disconnect();
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const docsOnly = args.has("--docs-only");
  const mongoOnly = args.has("--mongo-only");
  const data = rows();

  if (!mongoOnly) {
    writeDocs(data);
    console.log("");
  }

  if (!docsOnly) {
    try {
      await seedMongo(data);
    } catch (err) {
      console.error("Mongo seed failed:", err instanceof Error ? err.message : err);
      process.exitCode = 1;
      return;
    }
  }

  console.log("");
  console.log("Shared password: nectar2026");
  console.table(
    data
      .filter((r) => r.visibleOnLogin)
      .map((r) => ({
        role: r.roleLabel,
        plant: r.plant,
        email: r.email,
        password: r.password,
      })),
  );
}

main();
